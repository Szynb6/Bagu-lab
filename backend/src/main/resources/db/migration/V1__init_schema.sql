-- ============================================================================
-- Bagu Platform V1.0 初始化脚本（PostgreSQL 17 · 6 张核心用户端表）
-- 注：pg_trgm 扩展已由超级用户在 bagu_db 中预先启用
-- ============================================================================

-- 1. 用户表 sys_user
CREATE TABLE IF NOT EXISTS sys_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(120) NOT NULL,
    nickname        VARCHAR(60)  NOT NULL DEFAULT '',
    role            VARCHAR(20)  NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
    daily_goal      INT          NOT NULL DEFAULT 20 CHECK (daily_goal > 0),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE sys_user IS '系统用户表';

-- 2. 知识模块表 kb_module（对应 01 JVM ~ 09 操作系统）
CREATE TABLE IF NOT EXISTS kb_module (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(50)  NOT NULL UNIQUE,
    title           VARCHAR(64)  NOT NULL,
    full_title      VARCHAR(128) NOT NULL,
    icon            VARCHAR(32)  NOT NULL DEFAULT 'book-open',
    description     TEXT         NOT NULL DEFAULT '',
    sprint_guide    TEXT         NOT NULL DEFAULT '',
    sort_order      INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_kb_module_sort ON kb_module (sort_order);
COMMENT ON TABLE kb_module IS '八股知识模块表（9大核心专题）';

-- 3. 模块篇目表 kb_chapter
CREATE TABLE IF NOT EXISTS kb_chapter (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id       BIGINT       NOT NULL REFERENCES kb_module(id) ON DELETE CASCADE,
    code            VARCHAR(64)  NOT NULL,
    title           VARCHAR(160) NOT NULL,
    summary         TEXT         NOT NULL DEFAULT '',
    sort_order      INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_kb_chapter_module_code UNIQUE (module_id, code)
);

CREATE INDEX IF NOT EXISTS idx_kb_chapter_module_sort ON kb_chapter (module_id, sort_order);
COMMENT ON TABLE kb_chapter IS '模块内篇目/子章节表';

-- 4. 核心题目表 kb_question
CREATE TABLE IF NOT EXISTS kb_question (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id       BIGINT       NOT NULL REFERENCES kb_module(id) ON DELETE CASCADE,
    chapter_id      BIGINT       REFERENCES kb_chapter(id) ON DELETE SET NULL,
    code            VARCHAR(24)  NOT NULL,
    priority        VARCHAR(8)   NOT NULL DEFAULT 'P1' CHECK (priority IN ('P0', 'P1', 'P2')),
    title           VARCHAR(400) NOT NULL,
    hints_json      JSONB        NOT NULL DEFAULT '[]'::jsonb,
    answer_md       TEXT         NOT NULL,
    images_json     JSONB        NOT NULL DEFAULT '[]'::jsonb,
    tags_json       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    has_table       BOOLEAN      NOT NULL DEFAULT FALSE,
    has_code        BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order      INT          NOT NULL DEFAULT 0,
    is_deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_kb_question_module_code UNIQUE (module_id, code)
);

CREATE INDEX IF NOT EXISTS idx_kb_question_filter ON kb_question (module_id, priority, sort_order) WHERE is_deleted = FALSE;
CREATE INDEX IF NOT EXISTS idx_kb_question_chapter ON kb_question (chapter_id, sort_order) WHERE is_deleted = FALSE;
CREATE INDEX IF NOT EXISTS idx_kb_question_title_trgm ON kb_question USING GIN (title gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_kb_question_answer_trgm ON kb_question USING GIN (answer_md gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_kb_question_tags_gin ON kb_question USING GIN (tags_json);
COMMENT ON TABLE kb_question IS '八股核心题目表（含 P0/P1/P2 分级、Markdown 答案、JSONB 图解与提示）';

-- 5. 用户学习与 SM-2 复习进度表 study_progress
CREATE TABLE IF NOT EXISTS study_progress (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
    question_id      BIGINT        NOT NULL REFERENCES kb_question(id) ON DELETE CASCADE,
    status           SMALLINT      NOT NULL DEFAULT 0 CHECK (status IN (0, 1, 2, 3)),
    ease_factor      NUMERIC(4, 2) NOT NULL DEFAULT 2.50,
    interval_days    INT           NOT NULL DEFAULT 0,
    repetitions      INT           NOT NULL DEFAULT 0,
    lapse_count      INT           NOT NULL DEFAULT 0,
    last_rating      SMALLINT      CHECK (last_rating IN (1, 2, 3, 4)),
    next_review_at   TIMESTAMPTZ,
    last_reviewed_at TIMESTAMPTZ,
    is_starred       BOOLEAN       NOT NULL DEFAULT FALSE,
    personal_note    TEXT          NOT NULL DEFAULT '',
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_study_progress_user_q UNIQUE (user_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_study_progress_due ON study_progress (user_id, next_review_at) WHERE next_review_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_study_progress_star ON study_progress (user_id, is_starred) WHERE is_starred = TRUE;
CREATE INDEX IF NOT EXISTS idx_study_progress_status ON study_progress (user_id, status);
COMMENT ON TABLE study_progress IS '用户单题 SM-2 间隔重复进度、收藏与个人助记表';

-- 6. 刷题复习流水表 study_review_log
CREATE TABLE IF NOT EXISTS study_review_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
    question_id     BIGINT      NOT NULL REFERENCES kb_question(id) ON DELETE CASCADE,
    rating          SMALLINT    NOT NULL CHECK (rating IN (1, 2, 3, 4)),
    duration_sec    INT         NOT NULL DEFAULT 0,
    prev_interval   INT         NOT NULL DEFAULT 0,
    next_interval   INT         NOT NULL DEFAULT 0,
    reviewed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_study_log_user_time ON study_review_log (user_id, reviewed_at DESC);
COMMENT ON TABLE study_review_log IS '复习打分流水表（用于每日统计、热力图校验与学习曲线分析）';
